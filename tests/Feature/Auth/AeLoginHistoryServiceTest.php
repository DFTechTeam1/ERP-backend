<?php

use App\Data\Auth\AfterEffect\LoginData;
use App\Data\User\AfterEffect\LoginHistoryListData;
use App\Data\User\AfterEffect\UserFormatData;
use App\Models\User;
use App\Services\AeLoginHistorService;
use App\Services\Auth\TokenService;
use Modules\Hrd\Models\AfterEffectLoginHistory;
use Modules\Hrd\Models\Employee;

use function Pest\Laravel\actingAs;
use function Pest\Laravel\assertDatabaseHas;
use function Pest\Laravel\getJson;
use function Pest\Laravel\postJson;

/**
 * AeLoginHistorService — records + reports After Effects plugin logins
 * (table: after_effect_login_histories). Requires `make test-migrate`.
 *
 * Browser/OS come from parseUserAgent(getUserAgentInfo()), which is "Unknown"
 * under the test runner (runningInConsole) — so os-content is not asserted.
 *
 * Only listHistories() is routed (GET /api/ae/login-logs); success()/failedLog()
 * run inside POST /api/auth/after-effect/login. detail()/summary() have no routes
 * yet, so they are covered at the service level only.
 */
function aeService(): AeLoginHistorService
{
    return app(AeLoginHistorService::class);
}

function aeUserFormat(User $user): UserFormatData
{
    return new UserFormatData(userName: $user->email, userId: (int) $user->id, userEmail: $user->email);
}

function aeUserWithEmployee(string $name): User
{
    $employee = Employee::factory()->withUser()->create(['name' => $name]);

    return User::where('employee_id', $employee->id)->firstOrFail();
}

/** Seed a history row (uid is auto-generated by the model observer). */
function aeLog(array $attrs = []): AfterEffectLoginHistory
{
    return AfterEffectLoginHistory::create(array_merge([
        'user_id' => User::factory()->create()->id,
        'os' => 'Windows',
        'ip_address' => '127.0.0.1',
        'is_success' => true,
        'login_at' => now(),
        'refresh_token_expires_at' => now()->addDays(7),
    ], $attrs));
}

describe('failedLog', function () {
    it('records a failed login attempt against the account', function () {
        $user = User::factory()->create();

        aeService()->failedLog(aeUserFormat($user), 'Password did not match');

        assertDatabaseHas('after_effect_login_histories', [
            'user_id' => $user->id,
            'is_success' => false,
            'failure_reason' => 'Password did not match',
            'ip_address' => '', // no HTTP request in console -> empty client ip
        ]);
    });
});

describe('success', function () {
    it('records a successful login with the AE version and token expiry', function () {
        $user = User::factory()->create();
        $payload = new LoginData(email: $user->email, password: 'x', version: '2.5.0');

        aeService()->success(aeUserFormat($user), $payload, '2026-10-23 10:00:00');

        assertDatabaseHas('after_effect_login_histories', [
            'user_id' => $user->id,
            'is_success' => true,
            'ae_version' => '2.5.0',
            'refresh_token_expires_at' => '2026-10-23 10:00:00',
        ]);
        expect(AfterEffectLoginHistory::where('user_id', $user->id)->value('login_at'))->not->toBeNull();
    });

    it('defaults the AE version to "-" when the payload omits it', function () {
        $user = User::factory()->create();
        $payload = new LoginData(email: $user->email, password: 'x', version: null);

        aeService()->success(aeUserFormat($user), $payload, '2026-10-23 10:00:00');

        assertDatabaseHas('after_effect_login_histories', ['user_id' => $user->id, 'ae_version' => '-']);
    });
});

describe('listHistories', function () {
    it('returns a paginated, formatted list with the total count', function () {
        $user = User::factory()->create();
        aeLog(['user_id' => $user->id, 'is_success' => true]);
        aeLog(['user_id' => $user->id, 'is_success' => false, 'login_at' => null, 'refresh_token_expires_at' => null]);

        request()->merge(['limit' => 10, 'page' => 1]);
        $response = aeService()->listHistories();

        expect($response['totalData'])->toBe(2)
            ->and($response['paginated'])->toHaveCount(2)
            ->and($response['paginated']->first())->toBeInstanceOf(LoginHistoryListData::class);
    });

    it('filters by status (failed|success)', function () {
        $user = User::factory()->create();
        aeLog(['user_id' => $user->id, 'is_success' => true]);
        aeLog(['user_id' => $user->id, 'is_success' => false, 'login_at' => null, 'refresh_token_expires_at' => null]);

        request()->merge(['limit' => 10, 'page' => 1, 'status' => 'failed']);
        $response = aeService()->listHistories();

        expect($response['totalData'])->toBe(1)
            ->and($response['paginated']->first()->login_successful)->toBeFalse();
    });

    it('filters by search on the employee name', function () {
        $zola = aeUserWithEmployee('Zola Developer');
        $other = aeUserWithEmployee('Someone Else');
        aeLog(['user_id' => $zola->id]);
        aeLog(['user_id' => $other->id]);

        request()->merge(['limit' => 10, 'page' => 1, 'search' => 'Zola']);
        $response = aeService()->listHistories();

        expect($response['totalData'])->toBe(1)
            ->and($response['paginated']->first()->user_name)->toBe('Zola Developer');
    });

    it('filters by a date range on login_at', function () {
        $user = User::factory()->create();
        aeLog(['user_id' => $user->id, 'login_at' => '2026-10-10 10:00:00']);
        aeLog(['user_id' => $user->id, 'login_at' => '2026-10-20 10:00:00']);

        request()->merge(['limit' => 10, 'page' => 1, 'date_from' => '2026-10-09', 'date_to' => '2026-10-12']);
        $response = aeService()->listHistories();

        expect($response['totalData'])->toBe(1);
    });
});

describe('detail', function () {
    it('returns the row matching the given uid (not merely the first row)', function () {
        $user = User::factory()->create();
        aeLog(['user_id' => $user->id, 'os' => 'Windows']);
        $target = aeLog(['user_id' => $user->id, 'os' => 'Mac OS']);

        $response = aeService()->detail($target->uid);

        expect($response['uid'])->toBe($target->uid)
            ->and($response['os'])->toBe('Mac OS');
    });
});

describe('summary', function () {
    it('aggregates totals, successes, failures, unique users, active tokens and today', function () {
        $u1 = User::factory()->create();
        $u2 = User::factory()->create();

        // u1: one active success (future token) + one failure (no token)
        aeLog(['user_id' => $u1->id, 'is_success' => true, 'refresh_token_expires_at' => now()->addDays(7), 'login_at' => now()]);
        aeLog(['user_id' => $u1->id, 'is_success' => false, 'refresh_token_expires_at' => null, 'login_at' => null]);
        // u2: a success whose token already expired
        aeLog(['user_id' => $u2->id, 'is_success' => true, 'refresh_token_expires_at' => now()->subDay(), 'login_at' => now()]);

        $response = aeService()->summary();

        expect($response['total'])->toBe(3)
            ->and($response['successful'])->toBe(2)
            ->and($response['failed'])->toBe(1)
            ->and($response['unique_users'])->toBe(2)
            ->and($response['active_tokens'])->toBe(1)  // only u1's future token
            ->and($response['today'])->toBe(2);         // the two logins with login_at = now
    });
});

