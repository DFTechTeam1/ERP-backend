describe('http', function () {
    it('[e2e] lists AE login histories at GET /api/ae/login-logs', function () {
        actingAs(User::factory()->create());
        aeLog(['user_id' => User::factory()->create()->id]);

        getJson('/api/ae/login-logs?limit=10&page=1')
            ->assertSuccessful()
            ->assertJsonStructure(['data' => ['paginated', 'totalData']]);
    });

    it('[e2e] requires authentication for the login-logs endpoint', function () {
        getJson('/api/ae/login-logs?limit=10&page=1')->assertUnauthorized();
    });

    it('[e2e] records a failed login via POST /api/auth/after-effect/login', function () {
        $user = User::factory()->create(); // factory password is "password"

        postJson('/api/auth/after-effect/login', [
            'email' => $user->email,
            'password' => 'wrong-password',
            'version' => '1.0.0',
        ])->assertStatus(400);

        assertDatabaseHas('after_effect_login_histories', [
            'user_id' => $user->id,
            'is_success' => false,
        ]);
    });

    it('[e2e] records a successful login via POST /api/auth/after-effect/login', function () {
        // mock the access-token signer so the test does not need RS256 keys
        $this->mock(TokenService::class, function ($mock) {
            $mock->shouldReceive('issueAccessToken')->andReturn('fake.access.token');
        });

        $user = User::factory()->create();

        postJson('/api/auth/after-effect/login', [
            'email' => $user->email,
            'password' => 'password',
            'version' => '3.1.0',
        ])->assertSuccessful();

        assertDatabaseHas('after_effect_login_histories', [
            'user_id' => $user->id,
            'is_success' => true,
            'ae_version' => '3.1.0',
        ]);
    });
});
